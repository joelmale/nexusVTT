import type {
  CampaignSession,
  PlanDependency,
  SessionPlan,
  SessionPlanStep,
} from '../ashes-of-veyra/types';
import { TIDES_CAMPAIGN_ID, tidesSessionId } from './campaign';

const ACT_1 = `${TIDES_CAMPAIGN_ID}-act-1`;
const ACT_2 = `${TIDES_CAMPAIGN_ID}-act-2`;
const ACT_3 = `${TIDES_CAMPAIGN_ID}-act-3`;

interface PlanInput {
  lastEdited: string;
  readiness: Array<{ label: string; complete: boolean }>;
  dependencies: PlanDependency[];
  steps: Omit<SessionPlanStep, 'id' | 'order'>[];
  notes: string[];
  playerFacingSummary: string;
  attachments: string[];
}

function buildPlan(sessionNumber: number, input: PlanInput): SessionPlan {
  const prefix = `${TIDES_CAMPAIGN_ID}-session-${sessionNumber}`;
  return {
    revision: 1,
    lastEdited: input.lastEdited,
    estimatedMinutes: input.steps.reduce(
      (total, step) => total + step.durationMinutes,
      0,
    ),
    readiness: input.readiness.map((item, index) => ({
      ...item,
      id: `${prefix}-ready-${index + 1}`,
    })),
    dependencies: input.dependencies,
    steps: input.steps.map((step, index) => ({
      ...step,
      id: `${prefix}-step-${index + 1}`,
      order: index + 1,
    })),
    notes: input.notes,
    playerFacingSummary: input.playerFacingSummary,
    attachments: input.attachments,
  };
}

