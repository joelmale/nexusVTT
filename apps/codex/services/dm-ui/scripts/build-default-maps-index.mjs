// Regenerates src/data/defaultMaps.ts from the VTT's bundled battle-map manifest
// (apps/vtt/public/assets/defaults/manifest.json).
// Run: node scripts/build-default-maps-index.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(
  here,
  '../../../../vtt/public/assets/defaults/manifest.json',
);
const target = resolve(here, '../src/data/defaultMaps.ts');

const manifest = JSON.parse(readFileSync(source, 'utf8'));
const items = manifest.maps?.items ?? [];

const rows = items
  .map((item) => ({
    id: String(item.id),
    name: String(item.name),
    category: item.category ? String(item.category) : 'other',
    path: String(item.path),
    thumbnail: String(item.thumbnail ?? item.path),
  }))
  .sort((a, b) => a.name.localeCompare(b.name, 'en', { numeric: true }));

const body = rows.map((row) => `  ${JSON.stringify(row)},`).join('\n');
writeFileSync(
  target,
  `// GENERATED by scripts/build-default-maps-index.mjs. Do not edit by hand.
// The VTT's bundled battle maps (apps/vtt/public/assets/defaults/manifest.json).
// Saved maps keep only the id (for example "default-map-1"); this index turns
// it back into a loadable image. Thumbnails are small (median 25 KB) and the
// full images are not (median 0.4 MB, up to 3.9 MB).
export interface DefaultMap {
  id: string;
  name: string;
  category: string;
  /** Full-size image, served from the gateway's asset root. */
  path: string;
  /** Small preview for pickers and cards. */
  thumbnail: string;
}

export const DEFAULT_MAPS: readonly DefaultMap[] = [
${body}
];

const BY_ID = new Map(DEFAULT_MAPS.map((map) => [map.id, map]));

export function findDefaultMap(id: string): DefaultMap | undefined {
  return BY_ID.get(id);
}
`,
);
console.log('Wrote ' + rows.length + ' maps to ' + target);
