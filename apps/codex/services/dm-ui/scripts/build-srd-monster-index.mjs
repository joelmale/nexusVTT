// Regenerates src/data/srdMonsters.ts from the SRD 5.1 (2014) monster data in
// packages/character-creator. Run: node scripts/build-srd-monster-index.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(
  here,
  '../../../../../packages/character-creator/src/data/srd/2014/5e-SRD-Monsters.json',
);
const target = resolve(here, '../src/data/srdMonsters.ts');

const monsters = JSON.parse(readFileSync(source, 'utf8'));

function crLabel(value) {
  if (value === 0.125) return '1/8';
  if (value === 0.25) return '1/4';
  if (value === 0.5) return '1/2';
  return String(value);
}

const walk = (speed) => {
  const match = /(\d+)/.exec(String(speed?.walk ?? ''));
  return match ? Number(match[1]) : 0;
};

const rows = monsters
  .map((m) => ({
    id: m.index,
    name: m.name,
    cr: crLabel(m.challenge_rating),
    type: m.type,
    size: m.size,
    ac: m.armor_class?.[0]?.value ?? 10,
    hp: m.hit_points,
    speed: walk(m.speed),
    abilities: [
      m.strength,
      m.dexterity,
      m.constitution,
      m.intelligence,
      m.wisdom,
      m.charisma,
    ],
  }))
  .sort((a, b) => a.name.localeCompare(b.name));

const body = rows.map((row) => `  ${JSON.stringify(row)},`).join('\n');
writeFileSync(
  target,
  `// GENERATED by scripts/build-srd-monster-index.mjs. Do not edit by hand.
// SRD 5.1 (2014) monsters, reduced to what encounter authoring needs.
export interface SrdMonster {
  id: string;
  name: string;
  /** Challenge rating label: '0', '1/8', '1/4', '1/2', '1' ... '30'. */
  cr: string;
  type: string;
  size: string;
  ac: number;
  hp: number;
  /** Walking speed in feet. */
  speed: number;
  /** STR, DEX, CON, INT, WIS, CHA scores. */
  abilities: [number, number, number, number, number, number];
}

export const SRD_MONSTERS: readonly SrdMonster[] = [
${body}
] as SrdMonster[];
`,
);
console.log(`Wrote ${rows.length} monsters to ${target}`);
